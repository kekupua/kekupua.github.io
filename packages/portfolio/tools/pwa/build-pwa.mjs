import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";

const manifest = JSON.parse(await readFile("dist/.vite/manifest.json", "utf8"));
// Follow eager imports only. Dynamic imports belong to the project that opens them.
function dependencies(key, files = new Set()) {
  const chunk = manifest[key];
  if (!chunk || files.has(`/${chunk.file}`)) return files;
  files.add(`/${chunk.file}`);
  for (const css of chunk.css || []) files.add(`/${css}`);
  for (const dependency of chunk.imports || []) dependencies(dependency, files);
  return files;
}
const pages = Object.fromEntries(
  [
    ["/", "index.html"],
    ["/eat/", "eat/index.html"],
    ["/learn/", "learn/index.html"],
    ["/maple/", "maple/index.html"],
    ["/mortgage/", "mortgage/index.html"],
  ].map(([url, key]) => [url, [url, ...dependencies(key)]]),
);
const routes = Object.fromEntries(
  [
    ["/random-hearthstone", "src/pages/HearthstoneRandomCard.jsx"],
    ["/recipesByGpt", "src/pages/Recipe/RecipeListPage.tsx"],
    ["/recipesByGpt/:id", "src/pages/Recipe/RecipeDetailPage.tsx"],
    ["/meal-prep", "src/pages/Recipe/MealPrepPage.tsx"],
  ].map(([route, key]) => {
    if (!manifest[key]) throw new Error(`Missing lazy project: ${key}`);
    return [route, [...dependencies(key)]];
  }),
);
const shell = [
  ...pages["/"],
  "/manifest.json",
  "/192.png",
  "/512.png",
  "/favicon.ico",
  "/offline.html",
];
const files = [];
async function walk(dir = "") {
  for (const entry of await readdir(`dist/${dir}`, { withFileTypes: true })) {
    const path = `${dir}${entry.name}`;
    if (entry.isDirectory()) {
      if (path !== ".vite") await walk(`${path}/`);
    } else if (
      /\.(?:js|css|png|jpe?g|webp|svg|ico|woff2?|json|webmanifest|mp3|html)$/.test(
        path,
      )
    ) {
      files.push(`/${path}`);
    }
  }
}
await walk();
// Only known build output is eligible. API responses, map tiles and remote images
// never enter Cache Storage. All projects share the same runtime budget.
const sizes = {};
const hash = createHash("sha256");
for (const url of files.sort()) {
  const bytes = await readFile(`dist${url}`);
  sizes[url] = bytes.byteLength;
  hash.update(url).update(bytes);
}
for (const page of Object.keys(pages)) sizes[page] = sizes[`${page}index.html`];
const template = await readFile("tools/pwa/worker.js", "utf8");
hash.update(template).update(JSON.stringify({ shell, pages, routes }));
const version = hash.digest("hex").slice(0, 16);
const config = {
  version,
  shell,
  pages,
  routes,
  sizes,
  maxEntries: 64,
  maxBytes: 12 * 1024 * 1024,
  maxFileBytes: 2 * 1024 * 1024,
};
await writeFile(
  "dist/sw.js",
  `/* Generated by tools/pwa/build-pwa.mjs */\nconst CONFIG = ${JSON.stringify(config)};\n${template}`,
);
await writeFile("dist/.vite/pwa.json", JSON.stringify(config, null, 2));
const bytes = shell.reduce((sum, url) => sum + sizes[url], 0);
console.log(
  `Portfolio offline shell: ${shell.length} files, ${(bytes / 1024).toFixed(1)} KiB; projects load on demand (${version})`,
);
